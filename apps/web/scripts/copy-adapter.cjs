function browserCopy(text, filename = '') {
  if (typeof text !== 'string') throw new TypeError('Browser copy adapter expects source text');
  const key = filename.replaceAll('\\', '/').replace(/^\.\//, '');
  const replacements = COPY_BY_FILE[key];
  if (!replacements) return text;
  let result = text;
  for (const [before, after] of replacements) result = result.replaceAll(before, after);
  return result;
}

